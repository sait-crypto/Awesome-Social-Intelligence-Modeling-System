LITERAL_TEXTS = {
    "en": dict(LITERAL_TRANSLATIONS_EN),
    "zh": {source: source for source in LITERAL_TRANSLATIONS_EN},
}


def localize_literal(language: Any, value: Any) -> Any:
    """Translate fixed GUI chrome while preserving user/database content."""
    if isinstance(value, list):
        return [localize_literal(language, item) for item in value]
    if isinstance(value, tuple):
        return tuple(localize_literal(language, item) for item in value)
    if not isinstance(value, str) or normalize_language(language) == "zh":
        return value
    if value in LITERAL_TRANSLATIONS_EN:
        return LITERAL_TRANSLATIONS_EN[value]
    translated = value
    for source in sorted(LITERAL_TRANSLATIONS_EN, key=len, reverse=True):
        if source in translated:
            translated = translated.replace(source, LITERAL_TRANSLATIONS_EN[source])
    return translated


def normalize_language(language: Any) -> str:
    value = str(language or "").strip().lower().replace("_", "-")
    if value.startswith("zh") or value in {"cn", "chinese", "中文"}:
        return "zh"
    return "en"


def translate(language: Any, key: str, **values: Any) -> str:
    normalized = normalize_language(language)
    template = TEXTS[normalized].get(key, TEXTS["en"].get(key, key))
    return template.format(**values) if values else template


INPUT_LIMIT_DEFAULTS = {"short": 512, "medium": 2_000, "long": 10_000}


def input_limit_tier(variable: str, field_type: str) -> str:
    if variable in {"abstract", "notes"}:
        return "long"
    if field_type == "text":
        return "medium"
    return "short"


def resolve_input_limit(settings: Mapping[str, Any], variable: str, field_type: str) -> int:
    tier = input_limit_tier(variable, field_type)
    ui_settings = settings.get("ui", {}) if isinstance(settings, Mapping) else {}
    raw = ui_settings.get(f"input_limit_{tier}", INPUT_LIMIT_DEFAULTS[tier])
    try:
        value = int(raw)
    except (TypeError, ValueError):
        value = INPUT_LIMIT_DEFAULTS[tier]
    return max(1, value)
