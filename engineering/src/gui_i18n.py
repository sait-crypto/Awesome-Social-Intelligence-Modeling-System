def _validate_catalogs() -> None:
    reference = set(TEXTS[SUPPORTED_LANGUAGES[0]])
    for language in SUPPORTED_LANGUAGES[1:]:
        current = set(TEXTS[language])
        if current != reference:
            missing = sorted(reference - current)
            extra = sorted(current - reference)
            raise ValueError(f"Unbalanced GUI translations for {language}: missing={missing}, extra={extra}")


_validate_catalogs()


